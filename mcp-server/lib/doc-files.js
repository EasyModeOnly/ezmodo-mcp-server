/**
 * Documents as local files (E-304 #3453), after lib/design-files.js (E-279).
 *
 * In a checkout, get_document writes a document's markdown to
 * `.ezmodo/docs/<slug>.md`. Beside it, `<slug>.meta.json` records the
 * document's id, the updatedAt it was downloaded at and a hash of the file as
 * downloaded. The hash tells "the agent edited this" from "this is what the
 * server has", so a re-download never silently discards unpushed work, and
 * `manage_document update fromFile:true` knows what to push and against which
 * version.
 *
 * Every read and write refuses symlinks and stays inside `.ezmodo/docs`
 * (E-297): a committed `.ezmodo/docs/x.md -> ~/.ssh/id_ed25519` must not turn
 * a push into an upload of the key.
 */

import crypto from 'crypto';
import path from 'path';
import { ezmodoSubdir, isInside, readFileNoFollow, writeFileNoFollow } from './local-paths.js';

const hash = (text) => crypto.createHash('sha256').update(text ?? '', 'utf8').digest('hex');

/**
 * The file name (without .md) a document is saved under: its slug when that
 * is a plain slug, else its id when that is a plain id, else nothing. Both
 * come from the API and are attacker-influenced, so neither is trusted to be a
 * file name (E-297).
 */
export function safeFileStem(slug, id) {
  if (typeof slug === 'string' && /^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug)) return slug;
  if (typeof id === 'string' && /^[A-Za-z0-9_-]{1,128}$/.test(id)) return id;
  return null;
}

/** `.ezmodo/docs`, or null when this is not a tracked checkout. */
export async function docsRoot() {
  return ezmodoSubdir('docs');
}

function pathsFor(root, stem) {
  const file = path.resolve(root, `${stem}.md`);
  if (!isInside(root, file)) return null;
  return { file, meta: path.join(root, `${stem}.meta.json`), mine: path.join(root, `${stem}.mine.md`) };
}

async function readMeta(metaPath) {
  const text = await readFileNoFollow(metaPath);
  if (text == null) return null;
  try {
    return JSON.parse(text);
  } catch {
    return null;
  }
}

async function writeMeta(p, doc, text) {
  const meta = {
    id: doc.id,
    slug: doc.slug ?? null,
    updatedAt: doc.updatedAt,
    hash: hash(text),
    note: 'Written by the EzModo MCP server. Edit the .md file, then push it with ' +
      'manage_document action:"update" documentId fromFile:true. Do not edit this file.',
  };
  await writeFileNoFollow(p.meta, JSON.stringify(meta, null, 2) + '\n');
}

/**
 * Write a fetched document to `.ezmodo/docs/<stem>.md`.
 *
 * Returns null when there is no `.ezmodo` directory or no safe file name.
 * When the file holds edits that were never pushed, it is left alone unless
 * `overwriteLocal` is set, and the result says so with `localChanges: true`.
 */
export async function writeDocFile(doc, { overwriteLocal = false } = {}) {
  const root = await docsRoot();
  if (!root) return null;
  const stem = safeFileStem(doc.slug, doc.id);
  const p = stem && pathsFor(root, stem);
  if (!p) return null;

  if (!overwriteLocal) {
    const meta = await readMeta(p.meta);
    const current = await readFileNoFollow(p.file);
    // Only a file this server wrote, for this document, and edited since, is
    // protected. A file with no sidecar predates it and is overwritten as it
    // always was.
    if (meta?.id === doc.id && current != null && hash(current) !== meta.hash) {
      return { file: p.file, localChanges: true };
    }
  }
  const text = doc.content ?? '';
  await writeFileNoFollow(p.file, text);
  await writeMeta(p, doc, text);
  return { file: p.file };
}

/**
 * Read a downloaded document back: its file's text, the sidecar, and whether
 * the file was edited since download. Throws a message the agent can act on
 * when there is no checkout or the document was never downloaded here.
 */
export async function readDocFile(doc) {
  const root = await docsRoot();
  if (!root) {
    throw new Error(
      'fromFile needs a local .ezmodo directory, and there is none here. Send edits or content instead.'
    );
  }
  const stem = safeFileStem(doc.slug, doc.id);
  const p = stem && pathsFor(root, stem);
  const meta = p ? await readMeta(p.meta) : null;
  const text = p ? await readFileNoFollow(p.file) : null;
  if (!p || meta?.id !== doc.id || text == null) {
    throw new Error(
      `Document ${doc.id} has not been downloaded here. Call get_document documentId:"${doc.id}" ` +
        'first, edit the file it writes, then push it.'
    );
  }
  return { file: p.file, paths: p, meta, text, changed: hash(text) !== meta.hash };
}

/** After a push, the file holds the server's version again. */
export async function refreshDocFile(local, doc) {
  const text = doc.content ?? '';
  await writeFileNoFollow(local.paths.file, text);
  await writeMeta(local.paths, doc, text);
}

/**
 * A push lost the race: keep the agent's text as `<stem>.mine.md` and put the
 * server's latest in the file, so the agent reapplies its change to the
 * current version instead of overwriting it.
 */
export async function setAsideAndRefreshDoc(local, latest) {
  await writeFileNoFollow(local.paths.mine, local.text);
  await refreshDocFile(local, latest);
  return local.paths.mine;
}
